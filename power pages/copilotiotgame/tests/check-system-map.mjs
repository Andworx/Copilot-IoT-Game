import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";
const base = process.env.KIOSK_TEST_URL ?? "http://127.0.0.1:5183";
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 800, height: 480 } });
let mode = "thermostat", socket;
const writes = [], errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.route("**/api/**", async route => {
 const path = new URL(route.request().url()).pathname;
 if (route.request().method() !== "GET" && !path.endsWith("/negotiate")) writes.push(path);
 const body = path.endsWith("/negotiate") ? { connectionId:"map", connectionToken:"map", negotiateVersion:1, availableTransports:[{transport:"WebSockets",transferFormats:["Text"]}] } : { deviceSlug:mode,gameModeEnabled:false };
 await route.fulfill({contentType:"application/json",body:JSON.stringify(body)});
});
await page.routeWebSocket(/azurewebsites\.net\/api/, ws => ws.onMessage(message => { if (String(message).includes('"protocol"')) { socket=ws; ws.send("{}\x1e"); } }));
await mkdir("test-results/system-map", { recursive:true });
try {
 await page.goto(`${base}/kiosk/info`);
 await page.getByRole("button",{name:"Return to Smart Thermostat"}).waitFor();
 assert.equal(await page.locator(".map-node").count(),12);
 assert.equal(await page.locator(".map-node img").evaluateAll(images => images.every(i => i.complete && i.naturalWidth > 0)),true);
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
 await page.screenshot({path:"test-results/system-map/kiosk.png"});
 assert.equal(await page.locator(".map-how summary").evaluate(el => el.getBoundingClientRect().bottom <= innerHeight),true);
 for (const node of await page.locator(".map-node").all()) {
  await node.focus();
  assert.ok(await page.locator('.map-links path[data-active="true"]').count() > 0);
  await page.keyboard.press("Enter");
  await page.getByRole("dialog").waitFor();
  assert.ok(await page.locator(".map-details li").count() > 0);
  await page.keyboard.press("Tab");
  assert.equal(await page.evaluate(() => !!document.activeElement?.closest("dialog")),true);
  await page.keyboard.press("Escape");
  assert.equal(await node.evaluate(el => el === document.activeElement),true);
 }
 await page.locator('[data-node="functions"]').click();
 await page.screenshot({path:"test-results/system-map/details.png"});
 await page.getByRole("button",{name:"Close component details"}).click();
 await page.getByRole("button",{name:"Return to Smart Thermostat"}).click();
 await page.waitForURL("**/kiosk/thermostat");
 await page.getByRole("button",{name:"Connection and display options"}).click();
 await page.getByRole("menuitem",{name:/Info/}).click();
 await page.getByRole("heading",{name:"System Map"}).waitFor();
 mode="water-pump";
 socket.send(JSON.stringify({type:1,target:"deviceChanged",arguments:[{deviceSlug:mode}]})+"\x1e");
 await page.getByRole("button",{name:/Return to.*Pump/}).waitFor();
 assert.match(page.url(),/kiosk\/info$/);
 await page.evaluate(() => window.dispatchEvent(new Event("pageshow")));
 await page.waitForTimeout(200);
 assert.match(page.url(),/kiosk\/info$/);
 await page.getByRole("button",{name:/Return to.*Pump/}).click();
 await page.waitForURL("**/kiosk/water-pump");
 await page.goto(`${base}/`);
 await page.getByRole("heading",{name:"System Map"}).waitFor();
 await page.locator("summary").click();
 assert.equal(await page.locator(".map-how li").count(),3);
 await page.setViewportSize({width:390,height:844});
 await page.emulateMedia({reducedMotion:"reduce"});
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
 await page.locator('[data-node="prize"]').click();
 await page.getByRole("dialog").waitFor();
 await page.screenshot({path:"test-results/system-map/narrow-details.png"});
 await page.keyboard.press("Escape");
 await page.screenshot({path:"test-results/system-map/narrow.png",fullPage:true});
 const touch = await browser.newPage({viewport:{width:390,height:844},hasTouch:true});
 await touch.goto(`${base}/tests/system-map-preview.html`);
 await touch.locator('[data-node="pi"]').tap();
 await touch.getByRole("dialog").waitFor();
 await touch.getByRole("button",{name:"Close component details"}).tap();
 assert.equal(await touch.getByRole("dialog").count(),0);
 await touch.close();
 assert.deepEqual(writes,[]);
 assert.deepEqual(errors,[]);
 console.log("System Map passed: 12 nodes, links, keyboard/touch targets, dialogs, focus return, mode updates, resume, read-only navigation, 800x480 and narrow layouts.");
} finally { await browser.close(); }
